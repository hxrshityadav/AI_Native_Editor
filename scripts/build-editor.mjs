import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fork = join(root, "vendor/openreel");
const run = (args) => { const result = spawnSync(process.platform === "win32" ? "corepack.cmd" : "corepack", ["pnpm", ...args], { cwd: fork, stdio: "inherit", shell: process.platform === "win32", env: { ...process.env, COREPACK_ENABLE_DOWNLOAD_PROMPT: "0" } }); if (result.error) throw result.error; if (result.status !== 0) process.exit(result.status ?? 1); };
if (!existsSync(join(fork, "apps/web/node_modules/vite"))) run(["install", "--filter", "@openreel/web...", "--frozen-lockfile"]);
const whisperRequire = createRequire(realpathSync(join(fork, "apps/web/node_modules/@huggingface/transformers/package.json")));
const runtime = dirname(whisperRequire.resolve("onnxruntime-web"));
const runtimeOutput = join(fork, "apps/web/public/whisper-runtime");
mkdirSync(runtimeOutput, { recursive: true });
for (const filename of ["ort-wasm-simd-threaded.jsep.mjs", "ort-wasm-simd-threaded.jsep.wasm"]) cpSync(join(runtime, filename), join(runtimeOutput, filename));
cpSync(join(fork, "licenses/ONNXRUNTIME-LICENSE.txt"), join(runtimeOutput, "ONNXRUNTIME-LICENSE.txt"));
cpSync(join(fork, "apps/web/node_modules/@huggingface/transformers/LICENSE"), join(runtimeOutput, "TRANSFORMERS-LICENSE.txt"));
const mediaRequire = createRequire(realpathSync(join(fork, "packages/core/package.json")));
const mediaBundle = dirname(mediaRequire.resolve("mediabunny"));
const mediaOutput = join(fork, "apps/web/public/runtime");
mkdirSync(mediaOutput, { recursive: true });
cpSync(join(mediaBundle, "mediabunny.mjs"), join(mediaOutput, "mediabunny.mjs"));
cpSync(join(mediaBundle, "../../LICENSE"), join(mediaOutput, "MEDIABUNNY-LICENSE.txt"));
cpSync(join(mediaBundle, "../../src"), join(mediaOutput, "mediabunny-source"), { recursive: true });
writeFileSync(join(mediaOutput, "SOURCES.txt"), "Mediabunny 1.25.3 is unmodified and licensed under MPL-2.0. Its source is provided in mediabunny-source/ beside this notice. Upstream: https://github.com/Vanilagy/mediabunny\n");
run(["build"]);
const source = join(fork, "apps/web/dist"); const target = join(root, "public/editor");
if (resolve(target) !== resolve(root, "public", "editor")) throw new Error("Unexpected editor output directory");
rmSync(target, { recursive: true, force: true }); mkdirSync(target, { recursive: true }); cpSync(source, target, { recursive: true });
cpSync(join(fork, "LICENSE"), join(target, "OPENREEL-LICENSE.txt"));
const files = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]);
// The fork uses the licensed Reel Finisher font catalog, not the unused desktop Google font mirror.
for (const path of files(join(target, "fonts"))) if (/\.(?:woff2?|ttf|css)$/.test(path)) rmSync(path);
const assets = files(target).filter((path) => /\.(?:js|mjs|css|wasm|woff2?|ttf|json|svg|png|webp|txt)$/.test(path));
for (const path of assets.filter((path) => /\.(?:js|mjs)$/.test(path))) if (/import\(["']@ffmpeg\/|https:\/\/unpkg\.com\/@ffmpeg\/|ffmpeg-core\.(?:wasm|js)/.test(readFileSync(path, "utf8"))) throw new Error("Forbidden FFmpeg runtime in browser output");
const precache = ["/editor/index.html", ...assets.filter((path) => !path.endsWith("sw.js")).map((path) => "/editor/" + relative(target, path).replaceAll("\\", "/"))];
precache.push(...files(join(root, "public/fonts")).filter((path) => /\.(woff2?|ttf|otf|txt|md)$/.test(path)).map((path) => "/fonts/" + relative(join(root, "public/fonts"), path).replaceAll("\\", "/")));
const workerPath = join(target, "sw.js");
const buildHash = createHash("sha256").update(JSON.stringify(precache));
for (const url of precache) buildHash.update(readFileSync(join(root, "public", url.slice(1))));
const buildId = buildHash.digest("hex").slice(0, 12);
writeFileSync(workerPath, readFileSync(workerPath, "utf8").replaceAll("__BUILD_ID__", buildId));
writeFileSync(join(target, "precache.json"), JSON.stringify(precache));
writeFileSync(join(target, "upstream.json"), readFileSync(join(fork, "UPSTREAM.json")));
console.log(`Built local editor: ${precache.length} offline assets`);
